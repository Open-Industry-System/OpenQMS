async def test_execution_cross_factory_404(db, capa_d3_with_execution, default_factory):
    """Cross-factory execution returns 404."""
    capa, ex, user = capa_d3_with_execution

    # Create a different user in a different factory
    from app.models.factory import Factory
    from app.models.role import RoleDefinition

    other_factory = Factory(
        id=uuid.uuid4(),
        code="OTHER-FAC",
        name="Other Factory",
        is_active=True,
    )
    db.add(other_factory)
    await db.flush()

    role = RoleDefinition(
        id=uuid.uuid4(),
        role_key="test_role_other",
        name_zh="Other Role",
        name_en="Other Role",
        description="Test",
        is_system=False,
        is_editable=True,
        is_active=True,
    )
    db.add(role)
    await db.flush()

    other_user = User(
        user_id=uuid.uuid4(),
        username="other_user",
        display_name="Other User",
        email="other@example.com",
        password_hash="test_hash",
        role_id=role.id,
        legacy_role="viewer",
        is_active=True,
        factory_id=other_factory.id,
    )
    db.add(other_user)
    await db.flush()

    # The cross-factory check is based on capa_id vs execution.factory_id
    # We need to create a different CAPA in other_factory to test this
    other_capa = CAPAEightD(
        report_id=uuid.uuid4(),
        document_no="CAPA-OTHER",
        title="Other CAPA",
        product_line_code="DC-DC-100",
        factory_id=other_factory.id,
        status="D3_INTERIM",
        severity="serious",
    )
    db.add(other_capa)
    await db.flush()

    # Try to update execution with wrong capa_id (different factory)
    with pytest.raises(LookupError, match="执行记录不属于该 CAPA"):
        await update_execution(
            db,
            other_capa.report_id,
            uuid.UUID(ex["execution_id"]),
            other_user,
            {"result_status": "failed"},
        )