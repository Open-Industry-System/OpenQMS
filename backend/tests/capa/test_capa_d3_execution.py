async def test_manual_execution_null_advice_generation(db, capa_d3_with_done_report):
    """Manual execution has NULL advice_id and generation_id."""
    capa, report, user = capa_d3_with_done_report
    ex = await record_execution(
        db,
        capa.report_id,
        report.report_id,
        user,
        {
            "source": "manual",
            "measure_text": "隔离库位 A",
            "result_status": "in_progress",
        },
    )
    assert ex["source"] == "manual"
    assert ex["advice_id"] is None
    assert ex["generation_id"] is None


